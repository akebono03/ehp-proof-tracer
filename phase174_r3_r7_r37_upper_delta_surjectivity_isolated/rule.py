"""General upper EHP Delta surjectivity from four independently proved claims.

This is an isolated mathematical rule, not a public provider and not a source.
It does not produce GIVEN facts or assert that its prerequisites have proofs.
"""
from __future__ import annotations

from expression import GeneratorSymbol, HomotopyElement
from homotopy_groups import (
    TodaDeltaMap,
    TodaEHPExactnessWindow,
    TodaHopfInvariantMap,
    TodaPrimaryGroup,
)
from map_facts import EHP_DELTA_MAP, EHP_H_MAP
from phase165_r12_r11_prop42_unified import prop42_exactness_indices
from phase165_r12_r12_ehp_consequences import EHPImageEqualsKernelStatement
from phase165_r12_r2_quotient_rules import KernelMultipleStatement
from phase165_r14_r6_generic_iso import MapInjective, MapSurjective
from phase165_r3_recursive_search import GoalExpansion
from phase174_r3_r7_r25_prop27_isolated_inference.rule import (
    Prop27TypedHopfDeltaStatement,
    typed_specialization,
)
from proof import InferenceRule, PremisePattern, ProofRule
from toda_rules import TodaProp42ExactnessStatement


RULE_NAME = "injective Hopf and exact lower Delta kernel with cited Hopf-Delta generator imply upper Delta surjectivity"


def upper_delta_surjectivity_inputs(
    goal: object,
) -> tuple[
    MapInjective,
    EHPImageEqualsKernelStatement,
    KernelMultipleStatement,
    Prop27TypedHopfDeltaStatement,
] | None:
    """Require exact EHP indices and typed identity generator, never an arbitrary map."""
    if type(goal) is not MapSurjective or type(goal.map) is not TodaDeltaMap:
        return None
    upper = goal.map
    if (type(upper.source_group) is not TodaPrimaryGroup
            or type(upper.target_group) is not TodaPrimaryGroup):
        return None
    n = upper.target_group.sphere_dimension
    if type(n) is not int or n < 4 or n % 2:
        return None
    try:
        witness = typed_specialization(n)
    except (ValueError, TypeError):
        return None
    if witness.delta != upper or witness.absolute_coefficient != 2:
        return None
    hopf = witness.hopf
    lower_source = hopf.target_group
    lower_target = TodaPrimaryGroup(2 * n - 3, n - 1)
    lower = TodaDeltaMap(lower_source, lower_target)
    window = TodaEHPExactnessWindow(
        source_term=hopf.source_group,
        middle_term=lower_source,
        target_term=lower_target,
        first_map=EHP_H_MAP,
        second_map=EHP_DELTA_MAP,
    )
    if prop42_exactness_indices(TodaProp42ExactnessStatement(window)) != (
        n - 1, 2 * n - 1, "h_delta",
    ):
        return None
    identity = HomotopyElement(
        name="ι_" + str(2 * n - 1),
        dimension=2 * n - 1,
        source=2 * n - 1,
        target=2 * n - 1,
        generator=GeneratorSymbol(family="ι", index=2 * n - 1),
    )
    return (
        MapInjective(hopf),
        EHPImageEqualsKernelStatement(window),
        KernelMultipleStatement(lower, lower_source, identity, witness.absolute_coefficient),
        witness,
    )


def upper_delta_surjectivity_rule(goal: MapSurjective) -> InferenceRule:
    """Conclude onto Delta only if all four separate INFERENCE steps are proved.

    im H = ker Delta_lower = <2*iota>. Proposition 2.7 says
    H Delta_upper(iota) = +/-2*iota. For any y in codomain(Delta_upper),
    H(y) lies in the cyclic group generated by H Delta_upper(iota), so
    H(y - k Delta_upper(iota)) = 0. Since H is injective, y is in im Delta.
    """
    required = upper_delta_surjectivity_inputs(goal)
    if required is None:
        raise ValueError("invalid typed EHP upper Delta surjectivity goal")

    def guard(premises, bindings):
        return (
            len(premises) == 4
            and all(step.rule is ProofRule.INFERENCE for step in premises)
            and tuple(step.conclusion for step in premises) == required
            and upper_delta_surjectivity_inputs(goal) == required
        )

    return InferenceRule(
        name=RULE_NAME,
        description=(
            "If H is injective, im(H)=ker(lower Delta)=<2*iota>, and the "
            "independently cited even-dimensional Hopf-Delta formula gives "
            "H(upper Delta(iota))=+/-2*iota, then upper Delta is onto. "
            "Each fact must be proved by the ordinary source-first search."
        ),
        premise_patterns=(
            PremisePattern(
                statement_type=MapInjective,
                statement_pattern=required[0],
                proof_rule=ProofRule.INFERENCE,
            ),
            PremisePattern(
                statement_type=EHPImageEqualsKernelStatement,
                statement_pattern=required[1],
                proof_rule=ProofRule.INFERENCE,
            ),
            PremisePattern(
                statement_type=KernelMultipleStatement,
                statement_pattern=required[2],
                proof_rule=ProofRule.INFERENCE,
            ),
            PremisePattern(
                statement_type=Prop27TypedHopfDeltaStatement,
                statement_pattern=required[3],
                proof_rule=ProofRule.INFERENCE,
            ),
        ),
        conclusion_pattern=goal,
        match_guard=guard,
    )


def expand_upper_delta_surjectivity(
    goal: object,
) -> tuple[GoalExpansion, ...]:
    """Offer a conditional backward candidate; never construct a ProofStep."""
    required = upper_delta_surjectivity_inputs(goal)
    if required is None:
        return ()
    return (GoalExpansion(upper_delta_surjectivity_rule(goal), required),)
