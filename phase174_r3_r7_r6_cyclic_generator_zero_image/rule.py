"""Generic zero-image inference from a proved finite-cyclic generator and its image.

This is an isolated inference candidate. No statement is admitted as a GIVEN;
no production search provider or renderer is changed.
"""
from __future__ import annotations

from expression import Expression, Zero
from homotopy_groups import FiniteCyclicGroup, TodaPrimaryGroup, TodaSuspensionMap
from map_property_rules import ImageZeroStatement
from phase165_r14_r6_generic_iso import GeneratorImage
from phase165_r3_recursive_search import GoalExpansion
from proof import InferenceRule, PremisePattern, ProofRule, Relation, RelationType


RULE_NAME = "finite cyclic generator mapped to zero implies zero homomorphism image"


def cyclic_generator_zero_image_inputs(
    goal: object,
    presentation: object,
) -> tuple[Relation, GeneratorImage] | None:
    """Construct two unproved typed obligations without choosing a generator.

    The caller supplies a concrete, separately screened cyclic-presentation
    candidate. It remains a GOAL, not a verified group claim. Only a genuine
    suspension map with valid adjacent dimensions is used at this phase.
    """
    if not isinstance(goal, ImageZeroStatement):
        return None
    suspension = goal.map
    if not isinstance(suspension, TodaSuspensionMap):
        return None
    domain = suspension.source_group
    codomain = suspension.target_group
    if not isinstance(domain, TodaPrimaryGroup) or not isinstance(codomain, TodaPrimaryGroup):
        return None
    degree = domain.group_dimension
    sphere = domain.sphere_dimension
    if (type(degree) is not int or type(sphere) is not int
            or sphere < 2 or degree < sphere
            or codomain != TodaPrimaryGroup(degree + 1, sphere + 1)):
        return None
    if (not isinstance(presentation, Relation)
            or presentation.relation_type is not RelationType.EQUALITY
            or presentation.lhs != domain
            or not isinstance(presentation.rhs, FiniteCyclicGroup)):
        return None
    cyclic = presentation.rhs
    if (type(cyclic.order) is not int or cyclic.order < 2
            or not isinstance(cyclic.generator, Expression)
            or isinstance(cyclic.generator, Zero)):
        return None
    image_goal = GeneratorImage(
        map=suspension,
        source_generator=cyclic.generator,
        target_generator=Zero(),
    )
    return presentation, image_goal


def zero_image_from_cyclic_generator_rule(
    goal: ImageZeroStatement,
    presentation: Relation,
) -> InferenceRule:
    """Require independent inferred proofs of the presentation and E(g)=0."""
    required = cyclic_generator_zero_image_inputs(goal, presentation)
    if required is None:
        raise ValueError("invalid finite cyclic zero-image premises")

    def guard(premises, bindings):
        return (
            len(premises) == 2
            and all(step.rule is ProofRule.INFERENCE for step in premises)
            and tuple(step.conclusion for step in premises) == required
            and cyclic_generator_zero_image_inputs(goal, presentation) == required
            and isinstance(required[1].target_generator, Zero)
        )

    return InferenceRule(
        name=RULE_NAME,
        description=(
            "If a homomorphism has a separately proved finite-cyclic domain "
            "generated by g, and the independently inferred generator image "
            "is the typed zero element, every element maps to zero. "
            "Neither the domain presentation nor E(g)=0 is a new GIVEN."
        ),
        premise_patterns=(
            PremisePattern(
                proof_rule=ProofRule.INFERENCE,
                statement_type=Relation,
                relation_type=RelationType.EQUALITY,
                statement_pattern=required[0],
            ),
            PremisePattern(
                proof_rule=ProofRule.INFERENCE,
                statement_type=GeneratorImage,
                statement_pattern=required[1],
            ),
        ),
        conclusion_pattern=goal,
        match_guard=guard,
    )


def expand_zero_image_from_cyclic_generator(
    goal: object,
    presentation: object,
) -> tuple[GoalExpansion, ...]:
    """Return a backward candidate only; never assert a verified ProofStep."""
    required = cyclic_generator_zero_image_inputs(goal, presentation)
    if required is None:
        return ()
    return (GoalExpansion(
        rule=zero_image_from_cyclic_generator_rule(goal, presentation),
        subgoals=required,
    ),)
