from __future__ import annotations

from collections import Counter
from dataclasses import asdict, dataclass, is_dataclass
import json
from pathlib import Path

from phase165_r52_r9_shared_math import build_shared_typed_bridge
from phase165_r52_r16_web_citation_gate import screen_shared_proof_context
from proof import ProofRule
from unified_statement_registry import AssertionOrigin


TARGET_LOCATORS = ("Proposition 5.3", "Proposition 5.6")


def classify_content(content: object) -> str:
    if isinstance(content, dict) and "source_text" in content:
        return "SOURCE_ONLY"
    if type(content).__name__ == "TodaFixedStatementComponent":
        return "METADATA_ONLY"
    if is_dataclass(content) and not isinstance(content, type):
        return "TYPED_REGISTERED"
    return "OTHER"


def get_locator(reference: object) -> str:
    return str(getattr(reference, "locator", ""))


def reference_position(bridge: object, assertion: object) -> object:
    reference = bridge.registry.reference(assertion.reference_id)
    return getattr(reference, "publication_position", None)


def choose_target(bridge: object, locator: str) -> object:
    matches = []
    for assertion in bridge.registry._assertions.values():
        if assertion.origin is not AssertionOrigin.FIXED_STATEMENT:
            continue
        reference = bridge.registry.reference(assertion.reference_id)
        if locator in (get_locator(reference), getattr(reference, "title", None)):
            matches.append(assertion)
    if not matches:
        raise LookupError(f"No fixed assertion registered for {locator}")
    return max(matches, key=lambda item: (reference_position(bridge, item) or -1, getattr(item, "component_position", None) or -1))


def audit_target(bridge: object, locator: str) -> dict[str, object]:
    target = choose_target(bridge, locator)
    screened = screen_shared_proof_context(
        bridge,
        goal=object(),
        citing_assertion_id=target.assertion_id,
        explicit_publication_target=True,
    )
    rows = []
    for link in screened.proof_links:
        assertion = bridge.registry.assertion(link.assertion_id)
        reference = bridge.registry.reference(assertion.reference_id)
        rows.append({
            "assertion_id": assertion.assertion_id,
            "locator": get_locator(reference),
            "content_type": type(assertion.content).__name__,
            "category": classify_content(assertion.content),
            "publication_position": reference_position(bridge, assertion),
            "component_position": getattr(assertion, "component_position", None),
            "valid_given": bool(link.step is not None and link.step.rule is ProofRule.GIVEN and link.step.conclusion == assertion.content),
        })
    counts = Counter(row["category"] for row in rows)
    return {
        "target_locator": locator,
        "target_assertion_id": target.assertion_id,
        "target_reference_position": reference_position(bridge, target),
        "generated_link_count": len(rows),
        "generated_by_category": dict(sorted(counts.items())),
        "invalid_generated_links": sum(not row["valid_given"] for row in rows),
        "generated_same_target_locator": sum(row["locator"] == locator for row in rows),
        "generated_links": rows,
    }


def main() -> int:
    bridge = build_shared_typed_bridge()
    categories = Counter(classify_content(a.content) for a in bridge.registry._assertions.values())
    reports = [audit_target(bridge, locator) for locator in TARGET_LOCATORS]
    result = {
        "audit": "phase168-r2-6b-autogenerated-proof-link-audit",
        "production_code_modified": False,
        "raw_bridge_links": len(bridge.proof_links),
        "registered_content_categories_all_assertions": dict(sorted(categories.items())),
        "targets": reports,
    }
    directory = Path(__file__).resolve().parent / "output"
    directory.mkdir(exist_ok=True)
    output = directory / "autolink_audit.json"
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2, default=str) + "\n", encoding="utf-8")
    print(json.dumps({
        "raw_bridge_links": result["raw_bridge_links"],
        "registered_content_categories_all_assertions": result["registered_content_categories_all_assertions"],
        "targets": [{key: value for key, value in target.items() if key != "generated_links"} for target in reports],
    }, ensure_ascii=False, indent=2))
    print(f"JSON: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
