"""General finite-cyclic Hopf lift from independent, certified premises.

An injective Hopf homomorphism H:A -> B with B cyclic of order m and
H(x) a generator of B identifies A as cyclic of order m generated by x.
This module creates only GoalExpansion proposals; no GIVEN or proof leaf.
"""
from __future__ import annotations

from expression import MapApplication
from homotopy_groups import FiniteCyclicGroup, TodaHopfInvariantMap, TodaPrimaryGroup
from map_facts import EHP_H_MAP
from phase165_r12_r2_quotient_rules import CyclicStructureStatement
from phase165_r14_r6_generic_iso import MapInjective
from phase165_r3_recursive_search import GoalExpansion
from phase171_r2j_r2_cyclic_hopf_surjective.source import (
    _coordinates,
    _eligible_group_instance,
    _same_generator,
)
from phase168_r2_8_4_generic_specialization.specialization import (
    specialize_registered_higher_stem,
)
from phase171_r2i_eta_hopf_bridge.source import eligible_eta_hopf_chains
from proof import InferenceRule, PremisePattern, ProofRule, Relation, RelationType


RULE_NAME = "injective Hopf preimage of a finite cyclic generator is cyclic"


def hopf_lift_inputs(
    goal: object, codomain: object, image: object,
) -> tuple[MapInjective, Relation, Relation] | None:
    """Check EHP types and registered IDs of both generator spellings.

    Toda's cited nu-prime uses the Unicode prime and a decorated nu symbol;
    the DB goal uses an undecorated TeX generator code.  Either exact typed
    equality or the existing registered-ID resolver must certify identity.
    This is notation identity, not an inference that two arbitrary elements
    happen to be equal in a homotopy group.
    """
    if (not isinstance(goal, CyclicStructureStatement)
            or not isinstance(goal.group, TodaPrimaryGroup)
            or type(goal.order) is not int or goal.order < 2
            or not isinstance(codomain, Relation)
            or codomain.relation_type is not RelationType.EQUALITY
            or not isinstance(codomain.lhs, TodaPrimaryGroup)
            or not isinstance(codomain.rhs, FiniteCyclicGroup)
            or codomain.rhs.order != goal.order
            or not isinstance(image, Relation)
            or image.relation_type is not RelationType.EQUALITY
            or not isinstance(image.lhs, MapApplication)
            or image.lhs.map != EHP_H_MAP):
        return None
    group = goal.group
    q, n = group.group_dimension, group.sphere_dimension
    if (type(q) is not int or type(n) is not int
            or n < 2 or q < max(n, 2 * n - 1)
            or codomain.lhs != TodaPrimaryGroup(q, 2 * n - 1)
            or not _same_generator(goal.generator, image.lhs.expression, goal.order)
            or _coordinates(goal.generator) != (q, n)
            or _coordinates(image.rhs) != (q, 2 * n - 1)
            or _coordinates(codomain.rhs.generator) != (q, 2 * n - 1)
            or not _same_generator(codomain.rhs.generator, image.rhs, goal.order)):
        return None
    h = TodaHopfInvariantMap(group, codomain.lhs)
    return MapInjective(h), codomain, image


def hopf_lift_rule(
    goal: CyclicStructureStatement, codomain: Relation, image: Relation,
) -> InferenceRule:
    """Infer A=Z/m{x} only after all three actual INFERENCE proofs exist."""
    required = hopf_lift_inputs(goal, codomain, image)
    if required is None:
        raise ValueError("not a typed Hopf cyclic lift")

    def guard(premises, bindings):
        return (
            len(premises) == 3
            and all(step.rule is ProofRule.INFERENCE for step in premises)
            and tuple(step.conclusion for step in premises) == required
            and hopf_lift_inputs(goal, codomain, image) == required
        )

    return InferenceRule(
        name=RULE_NAME,
        description=(
            "For an injective Hopf group homomorphism, a domain element "
            "mapping to a generator of a separately proved cyclic codomain "
            "generates the domain and has the same finite order."
        ),
        premise_patterns=(
            PremisePattern(
                proof_rule=ProofRule.INFERENCE,
                statement_type=MapInjective,
                statement_pattern=required[0],
            ),
            PremisePattern(
                proof_rule=ProofRule.INFERENCE,
                statement_type=Relation,
                relation_type=RelationType.EQUALITY,
                statement_pattern=required[1],
            ),
            PremisePattern(
                proof_rule=ProofRule.INFERENCE,
                statement_type=Relation,
                relation_type=RelationType.EQUALITY,
                statement_pattern=required[2],
            ),
        ),
        conclusion_pattern=goal,
        match_guard=guard,
    )


def expand_cited_hopf_lift(
    goal: object, available: tuple[object, ...],
) -> tuple[GoalExpansion, ...]:
    """Find cited Hopf-image and earlier codomain-schema candidates only.

    The requested group is a goal, never the source of a proof.  The
    independently earlier higher-stem schema must specialize exactly to
    the proposed codomain, and the Hopf image must be another sourced chain.
    """
    if not isinstance(available, tuple) or not isinstance(goal, CyclicStructureStatement):
        return ()
    if not isinstance(goal.group, TodaPrimaryGroup):
        return ()
    q, n = goal.group.group_dimension, goal.group.sphere_dimension
    if type(q) is not int or type(n) is not int or n < 2 or q < 2 * n - 1:
        return ()
    target_group = TodaPrimaryGroup(q, 2 * n - 1)
    candidates: list[GoalExpansion] = []
    for chain in eligible_eta_hopf_chains(available):
        image = chain.conclusion
        if (not isinstance(image, Relation)
                or not isinstance(image.lhs, MapApplication)
                or not _same_generator(
                    goal.generator, image.lhs.expression, goal.order,
                )):
            continue
        for source in available:
            if not isinstance(source, Relation):
                continue
            codomain = specialize_registered_higher_stem(source, 2 * n - 1)
            if (codomain is None
                    or codomain.lhs != target_group
                    or not isinstance(codomain.rhs, FiniteCyclicGroup)
                    or codomain.rhs.order != goal.order
                    or not _eligible_group_instance(source, codomain)):
                continue
            required = hopf_lift_inputs(goal, codomain, image)
            if required is None:
                continue
            candidate = GoalExpansion(
                rule=hopf_lift_rule(goal, codomain, image),
                subgoals=required,
            )
            if not any(existing.subgoals == candidate.subgoals for existing in candidates):
                candidates.append(candidate)
    return tuple(candidates)
