"""Infer a finite cyclic group from proved cardinality and full generator order.

The requested group presentation is only a GOAL.  An exact typed generator
or a unique HyoujiGen presentation identity must match the proved element.
This module adds no GIVEN statement and no database-derived proof premise.
"""
from __future__ import annotations

from homotopy_groups import FiniteCyclicGroup, TodaPrimaryGroup
from phase165_r3_recursive_search import GoalExpansion
from phase168_r2_8_3_generator_identity.identity import same_registered_group_presentation
from phase169_r10e5_composite_generator_image.rule import _endpoints
from phase171_r2j_r4_r6_middle_cardinality.source import FiniteGroupCardinality
from phase171_r2j_r4_r7_nonzero_nu_order.source import FiniteElementOrder
from proof import InferenceRule, PremisePattern, ProofRule, Relation, RelationType


def cyclic_group_from_generator_order(
    cardinality: object,
    element_order: object,
    requested: object | None = None,
) -> Relation | None:
    """Construct a checked candidate; a matching ProofStep is still required.

    The general theorem is: a finite group of cardinality m with an element
    of order m is generated by that element.  HyoujiGen is consulted only to
    reconcile two typed spellings of a generator, not to provide its order.
    """
    if (
        not isinstance(cardinality, FiniteGroupCardinality)
        or not isinstance(element_order, FiniteElementOrder)
        or not isinstance(cardinality.group, TodaPrimaryGroup)
        or element_order.group != cardinality.group
        or type(cardinality.order) is not int
        or type(element_order.order) is not int
        or cardinality.order < 2
        or element_order.order != cardinality.order
        or type(cardinality.group.group_dimension) is not int
        or type(cardinality.group.sphere_dimension) is not int
        or _endpoints(element_order.element) != (
            cardinality.group.group_dimension,
            cardinality.group.sphere_dimension,
        )
    ):
        return None

    canonical_group = FiniteCyclicGroup(
        order=cardinality.order,
        generator=element_order.element,
    )
    canonical = Relation(
        lhs=cardinality.group,
        rhs=canonical_group,
        relation_type=RelationType.EQUALITY,
    )
    if requested is None:
        return canonical
    if (
        not isinstance(requested, Relation)
        or requested.relation_type is not RelationType.EQUALITY
        or requested.lhs != cardinality.group
        or not isinstance(requested.rhs, FiniteCyclicGroup)
        or type(requested.rhs.order) is not int
        or requested.rhs.order != cardinality.order
        or _endpoints(requested.rhs.generator) != (
            cardinality.group.group_dimension,
            cardinality.group.sphere_dimension,
        )
    ):
        return None
    if (
        requested.rhs.generator != element_order.element
        and not same_registered_group_presentation(
            canonical_group, requested.rhs,
        )
    ):
        return None
    return requested


def inferred_cyclic_group_rule(goal: Relation) -> InferenceRule:
    """Require both cardinality and element-order premises to be INFERENCE."""
    if (
        not isinstance(goal, Relation)
        or goal.relation_type is not RelationType.EQUALITY
        or not isinstance(goal.lhs, TodaPrimaryGroup)
        or not isinstance(goal.rhs, FiniteCyclicGroup)
        or type(goal.rhs.order) is not int
        or goal.rhs.order < 2
    ):
        raise ValueError("finite cyclic typed goal required")

    def guard(premises, bindings):
        return (
            len(premises) == 2
            and all(step.rule is ProofRule.INFERENCE for step in premises)
            and cyclic_group_from_generator_order(
                premises[0].conclusion,
                premises[1].conclusion,
                requested=goal,
            ) == goal
        )

    return InferenceRule(
        name="finite group generated by an element of full order",
        premise_patterns=(
            PremisePattern(
                proof_rule=ProofRule.INFERENCE,
                statement_type=FiniteGroupCardinality,
            ),
            PremisePattern(
                proof_rule=ProofRule.INFERENCE,
                statement_type=FiniteElementOrder,
            ),
        ),
        match_guard=guard,
        conclusion_pattern=goal,
    )


def expand_cyclic_group_from_full_element_order(
    goal: object,
    cardinality: object,
    element_order: object,
) -> tuple[GoalExpansion, ...]:
    """Produce only a typed backward inference obligation, never a leaf."""
    if cyclic_group_from_generator_order(
        cardinality, element_order, requested=goal,
    ) != goal or not isinstance(goal, Relation):
        return ()
    return (GoalExpansion(
        inferred_cyclic_group_rule(goal),
        (cardinality, element_order),
    ),)
