"""Read-only inventory of duplicate generic inference rules and discovery overlap."""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from phase165_r8_rule_provider import discover_inference_rules
from standard_production_applicability_catalog import build_standard_production_applicability_catalog


def rule_signature(rule):
    """Conservative textual signature; identical signature is a candidate, not a theorem."""
    return (type(rule.conclusion_pattern).__name__, repr(rule.conclusion_pattern),
            tuple((repr(p.statement_type), repr(p.relation_type), repr(p.relation_pattern),
                   repr(p.statement_pattern)) for p in rule.premise_patterns))


def grouping(records, index):
    groups = defaultdict(list)
    for record in records:
        groups[record[index]].append(record[0])
    return [sorted(names) for names in groups.values() if len(names) > 1]


def main():
    root = Path(__file__).resolve().parent
    rules, discovery = discover_inference_rules()
    catalog = build_standard_production_applicability_catalog()
    entries = catalog.entries()
    catalog_records = [(e.key, e.rule.name, repr(rule_signature(e.rule)), id(e.rule)) for e in entries]
    discovery_records = [(f'discovery:{i}:{rule.name}', rule.name, repr(rule_signature(rule)), id(rule))
                         for i, rule in enumerate(rules)]
    catalog_names = {e.rule.name for e in entries}
    discovery_names = {r.name for r in rules}
    names = defaultdict(list)
    for e in entries:
        names[e.rule.name].append(e.key)
    report = {
        'phase': '165 rule duplicate R5', 'mode': 'READ_ONLY',
        'catalog_entries': len(entries), 'discovered_rules': len(rules),
        'catalog_unique_keys': len({e.key for e in entries}),
        'catalog_duplicate_name_groups': grouping(catalog_records, 1),
        'catalog_duplicate_signature_candidates': grouping(catalog_records, 2),
        'catalog_shared_object_groups': grouping(catalog_records, 3),
        'discovery_duplicate_name_groups': grouping(discovery_records, 1),
        'discovery_duplicate_signature_candidates': grouping(discovery_records, 2),
        'catalog_discovery_name_overlap': sorted(catalog_names & discovery_names),
        'catalog_only_rule_names': sorted(catalog_names - discovery_names),
        'discovery_only_rule_names': sorted(discovery_names - catalog_names),
        'dedicated_pi43_names_in_catalog': sorted({e.rule.name for e in entries if e.rule.name in {
            'Toda pi_4^3 Delta image generated by twice eta_2',
            'Toda pi_4^3 finite cyclic quotient calculation',
            'Toda pi_4^3 E-H exactness zero-right suspension surjectivity',
            'Toda pi_4^3 exactness Delta image equals E kernel',
            'Toda pi_4^3 eta_3 generator notation',
            'Toda 4.5 pi_4^3 finite-cyclic transport',
        }}),
        'discovery_modules': list(discovery.modules),
        'interpretation': 'Signature equality is a review candidate, not mathematical equivalence; name overlap is not proof of duplicated registration.',
        'full_pytest_run': False,
    }
    dest = root / 'audit_result.json'
    dest.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    summary = {k: (len(v) if isinstance(v, list) else v) for k, v in report.items()
               if k not in ('catalog_only_rule_names', 'discovery_only_rule_names', 'catalog_discovery_name_overlap')}
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print('Audit saved:', dest)
    return report


if __name__ == '__main__':
    main()
