def patch_function(name: str, function: str, old_fragment: str, new_fragment: str) -> str:
    file = ROOT / name
    source = file.read_text(encoding='utf-8')
    tree = ast.parse(source)
    matching = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == function]
    if len(matching) != 1:
        raise ValueError('Expected exactly one ' + function)
    node = matching[0]
    lines = source.splitlines(keepends=True)
    original = ''.join(lines[node.lineno - 1:node.end_lineno])
    if original.count(old_fragment) != 1:
        raise ValueError('Unexpected function body ' + function)
    new_func = original.replace(old_fragment, new_fragment)
    updated = ''.join(lines[:node.lineno - 1]) + new_func + ''.join(lines[node.end_lineno:])
    ast.parse(updated)
    return updated

