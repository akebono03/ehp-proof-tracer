"""Source-first, isolated Delta surjectivity from a verified full image.

A proof that im(Delta) is freely generated by g and a separate proof
that its codomain is freely generated by exactly the same typed g imply
surjectivity. This module proposes subgoals; it never asserts a GIVEN or
registers with the public search provider during R18.
"""
from __future__ import annotations

from homotopy_groups import (
    FreeCyclicGroup,
    TodaDeltaMap,
    TodaEHPExactnessWindow,
    TodaPrimaryGroup,
)
from map_facts import EHP_DELTA_MAP, EHP_E_MAP
from phase165_r12_r11_prop42_unified import prop42_exactness_indices
from phase165_r14_r6_generic_iso import MapSurjective
from phase165_r3_recursive_search import GoalExpansion
from proof import InferenceRule, PremisePattern, ProofRule, Relation, RelationType
from toda_rules import TodaDeltaImageFreeCyclicStatement, TodaProp42ExactnessStatement


RULE_NAME = "typed free cyclic Delta image equals codomain implies surjectivity"


def delta_surjectivity_image_inputs(
    goal: object, codomain_presentation: object,
) -> tuple[Relation, TodaDeltaImageFreeCyclicStatement] | None:
    """Build two separate typed obligations for a valid EHP Delta map."""
    if not isinstance(goal, MapSurjective) or not isinstance(goal.map, TodaDeltaMap):
        return None
    delta = goal.map
    source = delta.source_group
    codomain = delta.target_group
    if not isinstance(source, TodaPrimaryGroup) or not isinstance(codomain, TodaPrimaryGroup):
        return None
    q = codomain.group_dimension
    n = codomain.sphere_dimension
    if (type(q) is not int or type(n) is not int or n < 2 or q < n):
        return None
    following = TodaPrimaryGroup(q + 1, n + 1)
    exact = TodaProp42ExactnessStatement(TodaEHPExactnessWindow(
        source_term=source,
        middle_term=codomain,
        target_term=following,
        first_map=EHP_DELTA_MAP,
        second_map=EHP_E_MAP,
    ))
    if prop42_exactness_indices(exact) != (n, q + 1, "delta_e"):
        return None
    if (not isinstance(codomain_presentation, Relation)
            or codomain_presentation.relation_type is not RelationType.EQUALITY
            or codomain_presentation.lhs != codomain
            or not isinstance(codomain_presentation.rhs, FreeCyclicGroup)):
        return None
    generator = codomain_presentation.rhs.generator
    from expression import Expression, Zero
    if not isinstance(generator, Expression) or isinstance(generator, Zero):
        return None
    image = TodaDeltaImageFreeCyclicStatement(
        map=delta, image_group=FreeCyclicGroup(generator),
    )
    return codomain_presentation, image


def delta_surjectivity_from_full_free_cyclic_image_rule(
    goal: MapSurjective, codomain_presentation: Relation,
) -> InferenceRule:
    """Require two independently INFERRED, exactly matching premises."""
    required = delta_surjectivity_image_inputs(goal, codomain_presentation)
    if required is None:
        raise ValueError("invalid Delta surjectivity image/codomain obligations")

    def guard(premises, bindings):
        return (
            len(premises) == 2
            and all(step.rule is ProofRule.INFERENCE for step in premises)
            and tuple(step.conclusion for step in premises) == required
            and delta_surjectivity_image_inputs(goal, codomain_presentation) == required
        )

    return InferenceRule(
        name=RULE_NAME,
        description=(
            "If the independently proved image of a well-typed Delta map "
            "equals the independently proved free-cyclic codomain with "
            "the same exact typed generator, Delta is surjective. "
            "Neither the codomain structure nor its image is a GIVEN."
        ),
        premise_patterns=(
            PremisePattern(
                statement_type=Relation,
                relation_type=RelationType.EQUALITY,
                statement_pattern=required[0],
                proof_rule=ProofRule.INFERENCE,
            ),
            PremisePattern(
                statement_type=TodaDeltaImageFreeCyclicStatement,
                statement_pattern=required[1],
                proof_rule=ProofRule.INFERENCE,
            ),
        ),
        conclusion_pattern=goal,
        match_guard=guard,
    )


def expand_delta_surjectivity_from_full_free_cyclic_image(
    goal: object, codomain_presentation: object,
) -> tuple[GoalExpansion, ...]:
    """One isolated backward candidate; not a verified ProofStep."""
    required = delta_surjectivity_image_inputs(goal, codomain_presentation)
    if required is None:
        return ()
    return (GoalExpansion(
        rule=delta_surjectivity_from_full_free_cyclic_image_rule(
            goal, codomain_presentation,
        ),
        subgoals=required,
    ),)
