def test_phase157_r4_r3_filter_is_noop_outside_representative_targets():
  root_step = _step(
    "Toda Proposition 5.15 pi_13^6 finite cyclic",
    "Proposition 5.15",
    _RelationLike(
      lhs=_TargetGroup(
        group_dimension=13,
        sphere_dimension=6,
      ),
      rhs="target",
    ),
  )
  step = _step(
    "Toda Proposition 5.15 pi_12^5 finite cyclic",
    "Proposition 5.15",
    "fixed group result",
  )
  entry = TodaGroupProofNarrativeReferenceEntry(
    number=1,
    reference=_reference(
      "Proposition 5.15"
    ),
    proof_steps=(
      step,
    ),
  )

  filtered = (
    filter_phase157_r4_representative_reference_entries_by_fixed_statement_boundary(
      (
        entry,
      ),
      root_step,
    )
  )

  assert filtered == (
    entry,
  )
