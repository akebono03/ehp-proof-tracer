def _families(
  catalog,
):
  families = defaultdict(
    list
  )

  for entry in catalog.entries():
    families[
      entry.rule.name
    ].append(
      entry
    )

  return {
    name: tuple(
      entries
    )
    for name, entries
    in families.items()
  }


def test_phase103_6d10_second_wave_assigns_all_29_family_categories():
  catalog = (
    build_standard_production_applicability_catalog()
  )

  families = _families(
    catalog
  )

  checked = 0

  for (
    expected_category,
    names,
  ) in SECOND_WAVE_EXPECTED.items():
    for name in names:
      entries = families[
        name
      ]

      assert all(
        entry.relevance_category
        is expected_category
        for entry in entries
      )

      checked += 1

  assert checked == 29


def test_phase103_6d10_second_wave_affects_exactly_408_catalog_entries():
  catalog = (
    build_standard_production_applicability_catalog()
  )

  families = _families(
    catalog
  )

  second_wave_names = {
    name
    for names
    in SECOND_WAVE_EXPECTED.values()
    for name in names
  }

  affected_entries = tuple(
    entry
    for name in second_wave_names
    for entry in families[
      name
    ]
  )

  assert len(
    affected_entries
  ) == 408

  assert all(
    entry.relevance_category
    is not RuleRelevanceCategory.UNCLASSIFIED
    for entry in affected_entries
  )


