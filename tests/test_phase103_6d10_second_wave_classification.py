def test_phase103_6d10_factory_provenance_uses_function_qualname():
  from standard_production_applicability_catalog import (
    _inference_rule_factory_name,
  )

  catalog = (
    build_standard_production_applicability_catalog()
  )

  families = _families(
    catalog
  )

  representative = families[
    "Toda EHP exactness zero-left Hopf injectivity"
  ][
    0
  ].rule

  builder = (
    representative.conclusion_builder
  )

  assert callable(
    builder
  )

  assert ".<locals>." in (
    builder.__qualname__
  )

  assert (
    _inference_rule_factory_name(
      representative
    )
    == (
      "toda_exactness_zero_left_implies_"
      "hopf_injective_inference_rule"
    )
  )
