"""Isolated, source-first typed specialization of Toda Proposition 2.7.

No public registration, no GIVEN facts, and no self-issued certified premise.
"""
from __future__ import annotations

from dataclasses import dataclass

from homotopy_groups import TodaDeltaMap, TodaHopfInvariantMap, TodaPrimaryGroup
from proof import InferenceRule, LiteratureReference, PremisePattern, ProofRule


PROP27_REFERENCE = LiteratureReference(
    label="Toda Proposition 2.7",
    author="H. Toda",
    title="Composition Methods in Homotopy Groups of Spheres",
    locator="Proposition 2.7",
)
RULE_NAME = "Toda Proposition 2.7 even-dimensional typed Hopf-Delta specialization"


@dataclass(frozen=True)
class Prop27GeneralTheoremPremise:
    """Theorem-schema obligation, not itself a proved fact or a GIVEN."""
    source_locator: str = "Proposition 2.7"
    only_even_n: bool = True
    sign_undetermined: bool = True


@dataclass(frozen=True)
class Prop27TypedHopfDeltaStatement:
    n: int
    delta: TodaDeltaMap
    hopf: TodaHopfInvariantMap
    source_iota_dimension: int
    target_iota_dimension: int
    absolute_coefficient: int
    sign_undetermined: bool


def typed_specialization(n: int) -> Prop27TypedHopfDeltaStatement:
    """Build typed data only: this operation never creates a ProofStep."""
    if type(n) is not int or n < 2 or n % 2:
        raise ValueError("Proposition 2.7 requires an even integer n >= 2")
    source = TodaPrimaryGroup(2 * n + 1, 2 * n + 1)
    middle = TodaPrimaryGroup(2 * n - 1, n)
    target = TodaPrimaryGroup(2 * n - 1, 2 * n - 1)
    return Prop27TypedHopfDeltaStatement(
        n=n,
        delta=TodaDeltaMap(source, middle),
        hopf=TodaHopfInvariantMap(middle, target),
        source_iota_dimension=2 * n + 1,
        target_iota_dimension=2 * n - 1,
        absolute_coefficient=2,
        sign_undetermined=True,
    )


def prop27_typed_specialization_rule(n: int) -> InferenceRule:
    """Conditional inference from an independently established cited schema.

    The rule does not construct or register the necessary schema premise.
    """
    conclusion = typed_specialization(n)
    required = Prop27GeneralTheoremPremise()

    def guard(premises, bindings):
        if len(premises) != 1:
            return False
        step = premises[0]
        previous = step.inference_rule
        if step.rule is not ProofRule.INFERENCE or step.conclusion != required:
            return False
        if not isinstance(previous, InferenceRule):
            return False
        citation = previous.literature_reference
        return (
            isinstance(citation, LiteratureReference)
            and citation.locator == "Proposition 2.7"
            and citation.label == PROP27_REFERENCE.label
            and previous is not rule
        )

    rule = InferenceRule(
        name=RULE_NAME,
        description=(
            "If an independently sourced and inferred Toda Proposition 2.7 "
            "general theorem premise is present, specialize it at even n. "
            "The result retains both EHP map types and the undetermined sign. "
            "No source premise is generated by this rule."
        ),
        premise_patterns=(PremisePattern(
            statement_type=Prop27GeneralTheoremPremise,
            statement_pattern=required,
            proof_rule=ProofRule.INFERENCE,
        ),),
        conclusion_pattern=conclusion,
        match_guard=guard,
        literature_reference=PROP27_REFERENCE,
    )
    return rule
