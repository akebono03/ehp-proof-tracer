"""Typed first-isomorphism and cyclic quotient inference (Phase 165 R12-R2).

These statements are proof goals, not trusted facts. In particular, creating a
statement does not certify the homomorphism, kernel, or surjectivity it describes.
"""
from __future__ import annotations

from dataclasses import dataclass

from map_property_rules import SurjectiveMapStatement
from proof import InferenceRule, PatternVariable, PremisePattern


@dataclass(frozen=True)
class HomomorphismPresentationStatement:
    """f: domain -> codomain with f(source_generator)=target_generator."""
    map: object
    domain: object
    codomain: object
    source_generator: object
    target_generator: object


@dataclass(frozen=True)
class KernelMultipleStatement:
    """ker(f) is the subgroup generated by multiple * source_generator."""
    map: object
    domain: object
    source_generator: object
    multiple: object

    def __post_init__(self):
        if isinstance(self.multiple, PatternVariable):
            return
        if type(self.multiple) is not int or self.multiple < 1:
            raise ValueError("multiple must be a positive integer")


@dataclass(frozen=True)
class QuotientIsomorphismStatement:
    """codomain ≅ domain / <multiple*source_generator>, with generators."""
    map: object
    domain: object
    codomain: object
    source_generator: object
    target_generator: object
    multiple: object

    def __post_init__(self):
        if isinstance(self.multiple, PatternVariable):
            return
        if type(self.multiple) is not int or self.multiple < 1:
            raise ValueError("multiple must be a positive integer")


@dataclass(frozen=True)
class CyclicStructureStatement:
    """order=None denotes an infinite cyclic group; positive int is finite."""
    group: object
    generator: object
    order: object

    def __post_init__(self):
        if isinstance(self.order, PatternVariable) or self.order is None:
            return
        if type(self.order) is not int or self.order < 1:
            raise ValueError("order must be None or a positive integer")


def first_isomorphism_quotient_inference_rule():
    """An onto homomorphism identifies the target with domain/kernel."""
    f = PatternVariable("map")
    a = PatternVariable("domain")
    b = PatternVariable("codomain")
    x = PatternVariable("source_generator")
    y = PatternVariable("target_generator")
    m = PatternVariable("multiple")
    return InferenceRule(
        name="first isomorphism theorem for generated kernel",
        description="An onto homomorphism identifies its codomain with the quotient by its kernel.",
        premise_patterns=(
            PremisePattern(
                statement_type=HomomorphismPresentationStatement,
                statement_pattern=HomomorphismPresentationStatement(f, a, b, x, y),
            ),
            PremisePattern(
                statement_type=KernelMultipleStatement,
                statement_pattern=KernelMultipleStatement(f, a, x, m),
            ),
            PremisePattern(
                statement_type=SurjectiveMapStatement,
                statement_pattern=SurjectiveMapStatement(f),
            ),
        ),
        conclusion_pattern=QuotientIsomorphismStatement(f, a, b, x, y, m),
    )


def infinite_cyclic_quotient_structure_inference_rule():
    """Z/<m> is cyclic of order m; generator is the image of 1."""
    f = PatternVariable("map")
    a = PatternVariable("domain")
    b = PatternVariable("codomain")
    x = PatternVariable("source_generator")
    y = PatternVariable("target_generator")
    m = PatternVariable("multiple")
    return InferenceRule(
        name="infinite cyclic quotient structure",
        description="The quotient of an infinite cyclic group by its m-multiples is cyclic of order m.",
        premise_patterns=(
            PremisePattern(
                statement_type=QuotientIsomorphismStatement,
                statement_pattern=QuotientIsomorphismStatement(f, a, b, x, y, m),
            ),
            PremisePattern(
                statement_type=CyclicStructureStatement,
                statement_pattern=CyclicStructureStatement(a, x, None),
            ),
        ),
        conclusion_pattern=CyclicStructureStatement(b, y, m),
    )
