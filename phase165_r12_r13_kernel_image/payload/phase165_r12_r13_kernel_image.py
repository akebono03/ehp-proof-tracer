"""R12-R13: infer a concrete suspension kernel from a cited Delta image.

Never inserts a literature leaf; reverse proposals require a uniquely screened
signed Delta witness and a matching EHP exactness goal.
"""
from __future__ import annotations

from dataclasses import dataclass

from homotopy_groups import (
    FreeCyclicGroup,
    TodaDeltaMap,
    TodaEHPExactnessWindow,
    TodaPrimaryGroup,
    TodaSuspensionMap,
)
from map_facts import EHP_DELTA_MAP, EHP_E_MAP
from phase165_r12_r11_prop42_unified import prop42_exactness_indices
from phase165_r12_r12_ehp_consequences import EHPImageEqualsKernelStatement
from phase165_r3_recursive_search import GoalExpansion
from proof import InferenceRule, PremisePattern, ProofRule
from toda_rules import (
    TodaDeltaImageFreeCyclicStatement,
    TodaDeltaImageUpToSignStatement,
    TodaProp42ExactnessStatement,
)
from unified_statement_registry import AssertionOrigin


@dataclass(frozen=True)
class SuspensionKernelFreeCyclicStatement:
    """Ker(E) as a subgroup generated by the given image generator."""
    map: TodaSuspensionMap
    kernel_group: FreeCyclicGroup


def delta_image_and_exactness_imply_kernel_inference_rule() -> InferenceRule:
    """Im(Delta)=<x> and Im(Delta)=Ker(E) imply Ker(E)=<x>."""
    def guard(premises, bindings):
        image, equality = (item.conclusion for item in premises)
        if not isinstance(image, TodaDeltaImageFreeCyclicStatement):
            return False
        if not isinstance(equality, EHPImageEqualsKernelStatement):
            return False
        window = equality.window
        return (
            window.first_map == EHP_DELTA_MAP
            and window.second_map == EHP_E_MAP
            and prop42_exactness_indices(TodaProp42ExactnessStatement(window)) is not None
            and image.map == TodaDeltaMap(window.source_term, window.middle_term)
            and isinstance(image.image_group, FreeCyclicGroup)
        )

    def build(premises):
        image, equality = (item.conclusion for item in premises)
        window = equality.window
        return SuspensionKernelFreeCyclicStatement(
            map=TodaSuspensionMap(window.middle_term, window.target_term),
            kernel_group=image.image_group,
        )

    return InferenceRule(
        name="EHP Delta image and exactness imply concrete suspension kernel",
        description="From Im(Delta)=<x> and exactness infer Ker(E)=<x>.",
        premise_patterns=(
            PremisePattern(statement_type=TodaDeltaImageFreeCyclicStatement),
            PremisePattern(statement_type=EHPImageEqualsKernelStatement),
        ),
        match_guard=guard,
        conclusion_builder=build,
    )


def expand_concrete_suspension_kernel(
    goal: object, available_statements: tuple[object, ...]
) -> tuple[GoalExpansion, ...]:
    """Bind Delta's generator from screened facts; never guess it from goal."""
    if not isinstance(available_statements, tuple):
        raise TypeError("available_statements must be a tuple")
    if not isinstance(goal, SuspensionKernelFreeCyclicStatement):
        return ()
    if not isinstance(goal.map, TodaSuspensionMap):
        return ()
    if not isinstance(goal.kernel_group, FreeCyclicGroup):
        return ()
    middle = goal.map.source_group
    target = goal.map.target_group
    if not isinstance(middle, TodaPrimaryGroup) or not isinstance(target, TodaPrimaryGroup):
        return ()
    n = middle.sphere_dimension
    i = target.group_dimension
    if type(n) is not int or type(i) is not int:
        return ()
    window = TodaEHPExactnessWindow(
        source_term=TodaPrimaryGroup(i + 1, 2 * n + 1),
        middle_term=middle,
        target_term=target,
        first_map=EHP_DELTA_MAP,
        second_map=EHP_E_MAP,
    )
    if prop42_exactness_indices(TodaProp42ExactnessStatement(window)) is None:
        return ()
    delta_map = TodaDeltaMap(window.source_term, window.middle_term)
    witness_matches = tuple(
        fact for fact in available_statements
        if isinstance(fact, TodaDeltaImageUpToSignStatement)
        and fact.map == delta_map
        and fact.positive_value == goal.kernel_group.generator
    )
    # Fail closed for missing and ambiguous signed Delta sources.
    if len(witness_matches) != 1:
        return ()
    image_goal = TodaDeltaImageFreeCyclicStatement(
        map=delta_map, image_group=goal.kernel_group,
    )
    exact_goal = EHPImageEqualsKernelStatement(window)
    return (GoalExpansion(
        delta_image_and_exactness_imply_kernel_inference_rule(),
        (image_goal, exact_goal),
    ),)


def build_concrete_kernel_provider(bridge):
    """Build the provider only from screened, identical registered GIVEN facts."""
    available = []
    for link in bridge.proof_links:
        step = link.step
        if step is None or step.rule is not ProofRule.GIVEN:
            continue
        assertion = bridge.registry.assertion(link.assertion_id)
        if assertion.origin is not AssertionOrigin.FIXED_STATEMENT:
            continue
        if step.conclusion != assertion.content:
            continue
        available.append(step.conclusion)

    def expand(goal):
        return expand_concrete_suspension_kernel(goal, tuple(available))

    return expand
